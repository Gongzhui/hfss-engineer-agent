"""Build a benchmark case: probe source, build answer book, build sandbox + manifest.

    uv run python benchmark/build_case.py --case siw_feed_l1 --stage all
    uv run python benchmark/build_case.py --case siw_feed_l1 --stage probe

Stages:
  probe    — read-only text scout of the source project (designs, literal
             variables, units) to help author case.json. Never launches AEDT.
  answer   — solve nominal + perturbed (broken) states through the hfss-mcp
             trial mechanism itself (product eats its own dogfood); writes
             answer/nominal_values.json, answer/perturbation.json,
             answer/metrics.json and real Touchstone exports.
  sandbox  — author sandbox/<case>_sandbox.aedt: strip saved solutions /
             reports / ReportManager / Documentation / preview, delete sibling
             designs, apply the deterministic perturbation; then write
             manifest.json locked to the sandbox project.
  all      — answer then sandbox (default).

Exit codes: 0 ok, 1 build error, 2 preflight error.
"""

from __future__ import annotations

import argparse
import json
import os
import shutil
import sys
import time
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

sys.path.insert(0, str(Path(__file__).resolve().parent))

from aedt_text import strip_aedt_text  # noqa: E402
from case_io import (  # noqa: E402
    Case,
    compute_perturbation,
    load_case,
    nominal_map,
    read_design_variables,
)
from procs import ansysedt_pids, kill_spawned  # noqa: E402

TERMINAL_STATES = {"completed", "failed", "cancelled", "interrupted"}
TRIAL_TIMEOUT_S = 1800.0


def log(msg: str) -> None:
    print(msg, flush=True)


def _utc_now() -> str:
    return datetime.now(UTC).isoformat()


# --------------------------------------------------------------------------
# stage: probe
# --------------------------------------------------------------------------
def stage_probe(case: Case) -> int:
    src = Path(case.source.project_path)
    if not src.is_file():
        log(f"PREFLIGHT FAIL: source project not found: {src}")
        return 2
    log(f"probe: {src}")
    text = src.read_text(encoding="utf-8", errors="replace")
    designs: list[str] = []
    for line in text.splitlines():
        if "$begin 'HFSSModel'" in line:
            designs.append("")  # marker; Name filled below
    log(f"HFSSModel blocks: {len(designs)}")
    for design in [case.source.design_name, *case.source.sibling_designs]:
        try:
            variables = read_design_variables(src, design)
        except ValueError as exc:
            log(f"  design {design!r}: {exc}")
            continue
        log(f"  design {design!r}: {len(variables)} literal variables")
        for name, (value, unit) in variables.items():
            mark = "*" if any(v.name == name for v in case.variables) else " "
            log(f"   {mark} {name} = {value}{unit}")
    log("(* = whitelisted in case.json)")
    return 0


# --------------------------------------------------------------------------
# stage: answer (product trial mechanism, in-process)
# --------------------------------------------------------------------------
def _manifest_dict(case: Case, project_path: Path, project_name: str) -> dict[str, Any]:
    from hfss_mcp.manifest import default_s11_metrics

    return {
        "schema_version": "1.1",
        "project_path": str(project_path.resolve()),
        "project_name": project_name,
        "design_name": case.source.design_name,
        "allowed_setups": [{"setup": case.source.setup, "sweep": case.source.sweep}],
        "parameters": [
            {"name": v.name, "unit": v.unit, "min": v.min, "max": v.max}
            for v in case.variables
        ],
        "allowed_metrics": default_s11_metrics(
            setup=case.source.setup,
            sweep=case.source.sweep,
            f_min_ghz=case.metrics.band_ghz[0],
            f_max_ghz=case.metrics.band_ghz[1],
            f_target_ghz=case.metrics.target_ghz,
            port=case.source.port,
        ),
        "stop_conditions": {
            "max_trials": case.budget.max_trials,
            "max_runtime_seconds": case.budget.max_runtime_seconds,
            "metric_targets": dict(case.metrics.thresholds),
        },
        "concurrency": {"mode": "serial", "max_concurrent": 1},
        "checkpoint": {"mode": "every_trial"},
        "notes": f"generated by benchmark/build_case.py for case {case.case_id}",
    }


def _run_trial(
    app: Any,
    mid: str,
    run_id: str,
    trial_id: str,
    case: Case,
    params: list[dict[str, Any]],
) -> dict[str, Any]:
    start = app.trial_start(
        manifest_id=mid,
        run_id=run_id,
        trial_id=trial_id,
        idempotency_key=f"{run_id}-{trial_id}",
        setup=case.source.setup,
        sweep=case.source.sweep,
        parameters={"values": params},
    )
    if not start.get("ok"):
        raise RuntimeError(f"trial_start rejected: {json.dumps(start)[:400]}")
    job_id = start["job_id"]
    log(f"  trial {trial_id}: job={job_id} params={[(p['name'], p['value']) for p in params]}")
    deadline = time.time() + TRIAL_TIMEOUT_S
    while True:
        state = app.trial_status(job_id)["job"]["state"]
        if state in TERMINAL_STATES:
            break
        if time.time() > deadline:
            raise TimeoutError(f"trial {trial_id} exceeded {TRIAL_TIMEOUT_S}s")
        time.sleep(5.0)
    res = app.trial_result(job_id)
    if res["state"] != "completed":
        raise RuntimeError(f"trial {trial_id} state={res['state']}: {json.dumps(res.get('error'))}")
    return res["result"]


def _harvest_touchstone(keep_dir: Path, since: float, dest_stem: Path) -> Path:
    candidates = [
        p
        for p in keep_dir.glob("*.s*p")
        if p.is_file() and p.stat().st_mtime >= since - 2.0
    ]
    if not candidates:
        raise RuntimeError(f"no Touchstone harvested in {keep_dir} (keep-dir hook did not fire)")
    newest = max(candidates, key=lambda p: p.stat().st_mtime)
    dest = dest_stem.with_suffix(newest.suffix)
    shutil.copy2(newest, dest)
    return dest


def stage_answer(case: Case) -> int:
    from hfss_mcp.app import AppContext
    from hfss_mcp.ids import file_sha256

    src = Path(case.source.project_path)
    if not src.is_file():
        log(f"PREFLIGHT FAIL: source project not found: {src}")
        return 2

    work = case.build_dir / "answer_work"
    ts_keep = case.build_dir / "ts_keep"
    for d in (work, ts_keep):
        if d.exists():
            shutil.rmtree(d, ignore_errors=True)
        d.mkdir(parents=True, exist_ok=True)
    case.answer_dir.mkdir(parents=True, exist_ok=True)

    # 1. nominal values + deterministic perturbation (text parse, no AEDT)
    all_vars = read_design_variables(src, case.source.design_name)
    nominal_all = {name: float(value) for name, (value, _u) in all_vars.items()}
    nominal = nominal_map(case)
    perturbed = compute_perturbation(case, nominal)
    (case.answer_dir / "nominal_values.json").write_text(
        json.dumps(
            {name: {"value": float(v), "unit": u} for name, (v, u) in all_vars.items()},
            indent=2,
        ),
        encoding="utf-8",
    )
    (case.answer_dir / "perturbation.json").write_text(
        json.dumps(
            {
                "seed": case.perturbation.seed,
                "min_pct": case.perturbation.min_pct,
                "max_pct": case.perturbation.max_pct,
                "variables": {
                    v.name: {
                        "unit": v.unit,
                        "nominal": nominal[v.name],
                        "perturbed": perturbed[v.name],
                        "pct": round((perturbed[v.name] / nominal[v.name] - 1.0) * 100.0, 2),
                    }
                    for v in case.variables
                },
            },
            indent=2,
        ),
        encoding="utf-8",
    )
    log(f"nominal: {nominal}")
    log(f"perturbed (seed={case.perturbation.seed}): {perturbed}")

    # 2. solve nominal + broken through the product trial mechanism
    answer_project = work / f"{case.case_id}_answer.aedt"
    shutil.copy2(src, answer_project)
    manifest = _manifest_dict(case, answer_project, answer_project.stem)

    os.environ["HFSS_MCP_ADAPTER"] = "pyaedt"
    os.environ["HFSS_MCP_DATA_DIR"] = str(work / "app_data")
    os.environ["HFSS_MCP_TOUCHSTONE_KEEP_DIR"] = str(ts_keep)

    pre_pids = ansysedt_pids()
    app = AppContext(data_dir=work / "app_data", adapter_name="pyaedt")
    evidence: dict[str, Any] = {}
    try:
        reg = app.register_manifest(manifest)
        mid = reg["manifest_id"]
        log(f"manifest registered: {mid[:16]}... (answer-build manifest, not the sandbox one)")
        for tag, values in (("nominal", nominal), ("broken", perturbed)):
            mark = time.time()
            t0 = time.time()
            params = [
                {"name": v.name, "value": values[v.name], "unit": v.unit}
                for v in case.variables
            ]
            result = _run_trial(
                app, mid, f"build_{case.case_id}", tag, case, params
            )
            ts = _harvest_touchstone(ts_keep, mark, case.answer_dir / tag)
            evidence[tag] = {
                "variables": {v.name: values[v.name] for v in case.variables},
                "metrics": result["metrics"],
                "solve_seconds": round(time.time() - t0, 1),
                "touchstone": {
                    "file": ts.name,
                    "sha256": file_sha256(ts),
                    "mtime": datetime.fromtimestamp(ts.stat().st_mtime, UTC).isoformat(),
                },
                "job": {"trial_id": result["trial_id"], "job_id": result["job_id"]},
            }
            log(f"  {tag}: metrics={result['metrics']} touchstone={ts.name}")
    finally:
        app.close()
        leftover = kill_spawned(pre_pids)
        if leftover:
            log(f"WARNING: ansysedt residue after answer build: {sorted(leftover)}")

    (case.answer_dir / "metrics.json").write_text(
        json.dumps(
            {
                "case_id": case.case_id,
                "generated_at": _utc_now(),
                "generator": "build_case.py --stage answer via hfss-mcp trial mechanism "
                "(in-process AppContext, supervisor worker, workspace copy)",
                "source_project": str(src),
                "nominal_variable_count": len(nominal_all),
                "results": evidence,
            },
            indent=2,
        ),
        encoding="utf-8",
    )
    log(f"answer book written: {case.answer_dir}")
    return 0


# --------------------------------------------------------------------------
# stage: sandbox
# --------------------------------------------------------------------------
def _strip_variable_metadata(case: Case, sandbox: Path, perturbed: dict[str, float]) -> None:
    """Rewrite whitelisted VariableProp lines to the plain 4-arg form.

    AEDT 2023 saves ``VariableProp('fl', 'UD', '', '0.2316mm', oa(...), sa(...), ta(...))``
    where the tuning metadata is centered on the *nominal* value — that leaks the
    answer. The plain form (as in the 2018 original) reopens cleanly.
    """
    lines = sandbox.read_text(encoding="utf-8").splitlines(keepends=True)
    rewritten = 0
    for i, line in enumerate(lines):
        for var in case.variables:
            if f"VariableProp('{var.name}'," in line and ", oa(" in line:
                indent = line[: len(line) - len(line.lstrip())]
                lines[i] = (
                    f"{indent}VariableProp('{var.name}', 'UD', '', "
                    f"'{perturbed[var.name]}{var.unit}')\n"
                )
                rewritten += 1
    if rewritten != len(case.variables):
        raise RuntimeError(
            f"expected to rewrite {len(case.variables)} VariableProp lines, did {rewritten}"
        )
    sandbox.write_text("".join(lines), encoding="utf-8")
    log(f"stripped oa/sa/ta tuning metadata on {rewritten} whitelisted VariableProp lines")


def stage_sandbox(case: Case) -> int:
    src = Path(case.source.project_path)
    if not src.is_file():
        log(f"PREFLIGHT FAIL: source project not found: {src}")
        return 2
    nominal = nominal_map(case)
    perturbed = compute_perturbation(case, nominal)
    log(f"perturbed values to apply: {perturbed}")

    case.sandbox_dir.mkdir(parents=True, exist_ok=True)

    # 1. fresh copy at the final sandbox path; drop only the giant base64 preview
    #    (pure speed: the preview is ~80% of the file and AEDT does not need it).
    #    Reports/solutions are handled via API below; full text-strip comes last.
    sandbox = case.sandbox_project
    shutil.copy2(src, sandbox)
    stale_lock = sandbox.with_suffix(".aedt.lock")
    if stale_lock.exists():
        stale_lock.unlink()
    counts = strip_aedt_text(sandbox, block_names=("ProjectPreview",))
    log(f"pre-strip (preview only) removals: {counts}")

    # 2. AEDT on the intact project: delete sibling designs, delete all reports
    #    via the ReportSetup COM module, set perturbed values, save.
    from ansys.aedt.core import Hfss

    pre_pids = ansysedt_pids()
    hfss = None
    try:
        hfss = Hfss(
            project=str(sandbox),
            design=case.source.design_name,
            non_graphical=True,
            new_desktop=True,
            close_on_exit=False,
        )
        log(f"designs before strip: {hfss.design_list}")
        for sibling in case.source.sibling_designs:
            ok = hfss.delete_design(sibling, fallback_design=case.source.design_name)
            log(f"delete_design({sibling!r}) -> {ok}")
            if not ok:
                raise RuntimeError(f"failed to delete sibling design {sibling!r}")
        hfss.set_active_design(case.source.design_name)
        # Direct COM module — pyaedt's post layer chokes enumerating plots here.
        report_mod = hfss.odesign.GetModule("ReportSetup")
        reports = list(report_mod.GetAllReportNames())
        log(f"reports to delete: {reports}")
        if reports:
            report_mod.DeleteReports(reports)
        for var in case.variables:
            new_value = f"{perturbed[var.name]}{var.unit}"
            hfss[var.name] = new_value
            log(f"set {var.name} = {new_value}")
        hfss.save_project()
        log(f"saved: {sandbox}")
    finally:
        if hfss is not None:
            try:
                hfss.release_desktop(close_projects=True, close_desktop=True)
            except Exception as exc:  # noqa: BLE001 — release must not mask errors
                log(f"release_desktop warning: {exc}")
        kill_spawned(pre_pids)

    # 3. text-strip whatever remains (Soln records, report shells, Documentation,
    #    regenerated preview); drop any results dir
    counts = strip_aedt_text(sandbox)
    log(f"post-strip removals: {counts}")
    for results_dir in case.sandbox_dir.glob("*.aedtresults"):
        shutil.rmtree(results_dir, ignore_errors=True)
        log(f"removed results dir: {results_dir.name}")

    # 3b. AEDT 2023 re-save attaches oa()/sa()/ta() tuning metadata to every
    #     VariableProp line; for whitelisted vars it is centered on the NOMINAL
    #     value ((Min+Max)/2 == nominal) — a leak. Rewrite those lines to the
    #     plain 4-argument form with the perturbed value.
    _strip_variable_metadata(case, sandbox, perturbed)

    # 4. validate: reopen read-only, check design list + perturbed values stuck.
    #    This also proves the trial worker (pyaedt) can open the stripped sandbox.
    pre_pids = ansysedt_pids()
    hfss = None
    try:
        hfss = Hfss(
            project=str(sandbox),
            design=case.source.design_name,
            non_graphical=True,
            new_desktop=True,
            close_on_exit=False,
        )
        designs = list(hfss.design_list)
        log(f"designs after strip: {designs}")
        if designs != [case.source.design_name]:
            raise RuntimeError(f"sandbox still holds designs {designs}")
        hfss.set_active_design(case.source.design_name)
        report_mod = hfss.odesign.GetModule("ReportSetup")
        remaining = list(report_mod.GetAllReportNames())
        if remaining:
            raise RuntimeError(f"sandbox still holds reports after strip: {remaining}")
        for var in case.variables:
            raw = str(hfss.variable_manager[var.name].expression)
            got = float(raw.removesuffix(var.unit))
            want = perturbed[var.name]
            if abs(got - want) > 1e-9:
                raise RuntimeError(f"{var.name}: readback {got} != perturbed {want}")
        log("variable readback matches perturbation table")
    finally:
        if hfss is not None:
            try:
                hfss.release_desktop(close_projects=True, close_desktop=True)
            except Exception as exc:  # noqa: BLE001
                log(f"release_desktop warning: {exc}")
        kill_spawned(pre_pids)

    # 4b. the validate reopen recreates AEDT sidecar dirs; leave the tree clean
    for junk in case.sandbox_dir.glob("*.aedtresults"):
        shutil.rmtree(junk, ignore_errors=True)
    for junk in case.sandbox_dir.glob("*.pyaedt"):
        shutil.rmtree(junk, ignore_errors=True)
    stale = sandbox.with_suffix(".aedt.lock")
    if stale.exists():
        stale.unlink()

    # 5. manifest locked to the sandbox project
    from hfss_mcp.manifest import load_manifest

    manifest = _manifest_dict(case, sandbox, sandbox.stem)
    validated = load_manifest(manifest)  # fail fast if the product rejects it
    case.manifest_path.write_text(
        json.dumps(manifest, indent=2) + "\n", encoding="utf-8"
    )
    log(f"manifest written: {case.manifest_path} (id={validated.manifest_id()[:16]}...)")
    log("sandbox build complete — run verify_case.py for the leak audit")
    return 0


# --------------------------------------------------------------------------
def main() -> int:
    parser = argparse.ArgumentParser(
        description="Build a benchmark case (answer book + sandbox + manifest).",
    )
    parser.add_argument("--case", required=True, help="case id under benchmark/cases/")
    parser.add_argument(
        "--stage",
        choices=["probe", "answer", "sandbox", "all"],
        default="all",
        help="build stage to run (default: all)",
    )
    args = parser.parse_args()

    try:
        case = load_case(args.case)
    except (FileNotFoundError, ValueError) as exc:
        log(f"PREFLIGHT FAIL: {exc}")
        return 2

    log(f"case: {case.case_id}  stage: {args.stage}")
    t0 = time.time()
    try:
        if args.stage == "probe":
            return stage_probe(case)
        if args.stage in ("answer", "all"):
            code = stage_answer(case)
            if code != 0:
                return code
        if args.stage in ("sandbox", "all"):
            code = stage_sandbox(case)
            if code != 0:
                return code
    except Exception as exc:
        log(f"BUILD FAILED: {type(exc).__name__}: {exc}")
        return 1
    log(f"done in {time.time() - t0:.1f}s")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
